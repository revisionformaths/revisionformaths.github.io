#!/usr/bin/env python3
"""Render assets/js/local-games.js from data/local-files.json.

`data/local-files.json` is the source of truth for both pages: every entry is
one file in `assets/games/`. This turns it into the plain list the pages read,
so no page ever patches its own JavaScript by hand.

    python3 scripts/build-local-list.py          # rewrite local-games.js
    python3 scripts/build-local-list.py --check  # exit 1 if it is stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "local-files.json"
OUT = ROOT / "assets" / "js" / "local-games.js"

HEADER = """/* Shared list of locally hosted HTML files for both search pages.
   GENERATED from data/local-files.json by scripts/build-local-list.py.
   Do not edit this file: edit the JSON and re-run the script, or let
   .github/workflows/import-files.yml do it. */

window.LOCAL_GAMES = [
"""


def js_string(value):
    """A double-quoted JS string literal that is also valid JSON."""
    return json.dumps(value, ensure_ascii=False)


def render(entries):
    rows = []
    for entry in entries:
        parts = [
            "file: " + js_string(entry["file"]),
            "title: " + js_string(entry["title"]),
        ]
        if entry.get("line"):
            parts.append("line: " + js_string(entry["line"]))
        if entry.get("featured"):
            parts.append("featured: true")
        source = entry.get("source") or {}
        if source.get("year"):
            parts.append("year: %d" % source["year"])
        if source.get("author"):
            parts.append("author: " + js_string(source["author"]))
        rows.append("    { " + ", ".join(parts) + " },")
    return HEADER + "\n".join(rows) + "\n];\n"


def main(argv):
    check = "--check" in argv
    data = json.loads(DATA.read_text(encoding="utf-8"))
    rendered = render(data["entries"])

    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if check:
        if current != rendered:
            print("local-games.js is stale: run python3 scripts/build-local-list.py", file=sys.stderr)
            return 1
        print("local-games.js matches data/local-files.json (%d entries)" % len(data["entries"]))
        return 0

    OUT.write_text(rendered, encoding="utf-8")
    print("wrote %s: %d entries" % (OUT.relative_to(ROOT), len(data["entries"])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
