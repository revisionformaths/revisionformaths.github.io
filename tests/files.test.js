/* The files page and the library behind it.
   Everything here is about one promise: every entry in data/local-files.json is
   a real file on disk, is regenerated into local-games.js, and is a file from
   this repository rather than a link to somebody else's page. */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8");
const DATA = JSON.parse(read("data/local-files.json"));

const MAX_FILE = 25 * 1024 * 1024; /* Cloudflare's per-file upload limit */
const BUDGET = 750 * 1024 * 1024;

/* Mirrors scripts/build-local-list.py, so a stale list is caught here. */
function renderList(entries, series) {
  const rows = entries.map((entry) => {
    const parts = ["file: " + JSON.stringify(entry.file), "title: " + JSON.stringify(entry.title)];
    if (entry.line) parts.push("line: " + JSON.stringify(entry.line));
    if (entry.featured) parts.push("featured: true");
    if (entry.series) parts.push("series: " + JSON.stringify(entry.series));
    if (entry.order) parts.push("order: " + entry.order);
    if (entry.players) parts.push("players: " + entry.players);
    const source = entry.source || {};
    if (source.year) parts.push("year: " + source.year);
    if (source.author) parts.push("author: " + JSON.stringify(source.author));
    return "    { " + parts.join(", ") + " },";
  });
  const groups = series.map(
    (group) =>
      "    { id: " + JSON.stringify(group.id) +
      ", name: " + JSON.stringify(group.name) +
      ", line: " + JSON.stringify(group.line || "") + " },"
  );
  return (
    "/* Shared list of locally hosted HTML files for both search pages.\n" +
    "   GENERATED from data/local-files.json by scripts/build-local-list.py.\n" +
    "   Do not edit this file: edit the JSON and re-run the script. */\n\n" +
    "window.LOCAL_GAMES = [\n" +
    rows.join("\n") +
    "\n];\n\nwindow.LOCAL_SERIES = [\n" +
    groups.join("\n") +
    "\n];\n"
  );
}

/* Resource references a document would actually fetch. */
const RESOURCE = /(?:src|href|poster)\s*=\s*["']([^"']+)["']/gi;
const STYLE_BLOCK = /<style[^>]*>([\s\S]*?)<\/style>/gi;
const CSS_URL = /url\(\s*["']?([^"')]+)["']?\s*\)/gi;

function fetchedFrom(html) {
  const refs = [];
  for (const match of html.matchAll(RESOURCE)) {
    const value = match[1].trim();
    if (!value || /^(data:|#|mailto:|javascript:)/i.test(value)) continue;
    refs.push(value);
  }
  for (const block of html.matchAll(STYLE_BLOCK)) {
    for (const match of block[1].matchAll(CSS_URL)) {
      const value = match[1].trim();
      if (value && !/^data:/i.test(value)) refs.push(value);
    }
  }
  return refs;
}

function fileChecks(check) {
  console.log("\nFILES — the offline library\n");

  const entries = DATA.entries;
  check("the file list is not empty", entries.length > 0, String(entries.length));

  /* Every entry has a file, and nothing on disk is missing from the list. */
  const missing = entries.filter((entry) => !fs.existsSync(path.join(ROOT, entry.file)));
  check(
    "every listed file exists",
    missing.length === 0,
    missing.slice(0, 3).map((e) => e.file).join(", ")
  );

  const listed = new Set(entries.map((entry) => entry.file));
  const onDisk = fs
    .readdirSync(path.join(ROOT, "assets", "games"))
    .filter((name) => /\.html?$/.test(name))
    .map((name) => "assets/games/" + name);
  const orphans = onDisk.filter((rel) => !listed.has(rel));
  check(
    "every bundled file is listed",
    orphans.length === 0,
    orphans.slice(0, 3).join(", ")
  );

  /* Paths and titles are unique, or two cards fight over one entry. */
  for (const [name, key] of [["file paths", "file"], ["titles", "title"]]) {
    const values = entries.map((entry) => entry[key].toLowerCase());
    check(
      "no two entries share " + name,
      new Set(values).size === values.length,
      String(values.length - new Set(values).size) + " duplicates"
    );
  }

  /* Sizes. A game is a file, not a bundle of files. */
  const tooBig = entries.filter((entry) => fs.statSync(path.join(ROOT, entry.file)).size > MAX_FILE);
  check(
    "no file is over the 25 MB per-file upload limit",
    tooBig.length === 0,
    tooBig.slice(0, 3).map((e) => e.file).join(", ")
  );

  const total = entries.reduce((sum, entry) => sum + fs.statSync(path.join(ROOT, entry.file)).size, 0);
  check(
    "the library stays inside the page budget",
    total < BUDGET,
    (total / 1048576).toFixed(0) + " MB of " + BUDGET / 1048576 + " MB"
  );

  /* Every entry is one file in this repository: nothing streamed, nothing
     handed to somebody else's page. */
  const offSite = entries.filter((entry) => !/^assets\/games\/[^/]+\.html?$/.test(entry.file));
  check(
    "every entry is one HTML file in assets/games/",
    offSite.length === 0,
    offSite.slice(0, 3).map((e) => e.file).join(", ")
  );

  const unattributed = entries.filter((entry) => {
    const source = entry.source || {};
    return source.kind !== "pack" || !/^https:\/\/github\.com\//.test(source.repo || "");
  });
  check(
    "every entry names the pack it came from",
    unattributed.length === 0,
    unattributed.slice(0, 3).map((e) => e.file).join(", ")
  );

  /* Every entry renders a card, so every one needs its screenshot. */
  const noThumb = entries.filter(
    (entry) => !fs.existsSync(path.join(ROOT, "assets", "img", "pack", path.basename(entry.file, path.extname(entry.file)) + ".jpg"))
  );
  check(
    "every file has a card image",
    noThumb.length === 0,
    noThumb.slice(0, 3).map((e) => path.basename(e.file)).join(", ")
  );

  /* Collections and two-player flags are curated data, so they have to add
     up: every series names real files, and every position is unique. */
  const series = DATA.series || [];
  check("some series are curated", series.length >= 8, String(series.length));

  const known = new Set(series.map((group) => group.id));
  const straySeries = entries.filter((entry) => entry.series && !known.has(entry.series));
  check("every entry belongs to a series that exists", straySeries.length === 0,
    straySeries.slice(0, 3).map((entry) => entry.file).join(", "));

  const broken = series.filter((group) => {
    const members = entries.filter((entry) => entry.series === group.id);
    if (members.length < 2) return true;
    const orders = members.map((entry) => entry.order || 0).sort((a, b) => a - b);
    return orders[0] !== 1 || orders.some((order, index) => order !== index + 1);
  });
  check("every series has two or more parts, numbered from one", broken.length === 0,
    broken.map((group) => group.id).join(", "));

  const shared = series.filter((group) => {
    const members = entries.filter((entry) => entry.series === group.id);
    return new Set(members.map((entry) => entry.title)).size !== members.length;
  });
  check("no series repeats a title", shared.length === 0, shared.map((group) => group.id).join(", "));

  const twoPlayer = entries.filter((entry) => entry.players === 2);
  check("two-player titles are marked", twoPlayer.length >= 10, String(twoPlayer.length));
  const oddPlayers = entries.filter((entry) => entry.players && entry.players !== 2);
  check("the only player count used is two", oddPlayers.length === 0,
    oddPlayers.slice(0, 3).map((entry) => entry.file).join(", "));

  /* The generated list must match the JSON it is generated from. */
  check(
    "local-games.js matches data/local-files.json",
    read("assets/js/local-games.js") === renderList(entries, DATA.series || []),
    "run python3 scripts/build-local-list.py"
  );

  /* And the page really reads it. */
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(read("assets/js/local-games.js"), sandbox);
  const list = sandbox.window.LOCAL_GAMES || [];
  check("the page script loads every entry", list.length === entries.length, list.length + " vs " + entries.length);
  check(
    "the entries the page loads point at real files",
    list.every((game) => fs.existsSync(path.join(ROOT, game.file)))
  );

  /* No import pipeline is shipped: files are added by hand, and nothing on a
     schedule can quietly grow the site. */
  check("no importer is left in the repo", !fs.existsSync(path.join(ROOT, "scripts/import-js13k.py")));
  check(
    "no workflow grows the library on its own",
    !fs.existsSync(path.join(ROOT, ".github/workflows/import-files.yml"))
  );
}

module.exports = { fileChecks };
