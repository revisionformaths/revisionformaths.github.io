/* The files page and its import pipeline.
   Everything here is about one promise: every entry in data/local-files.json is
   a real file on disk, is regenerated into local-games.js, and is a file that
   pulls nothing from the network. */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8");
const DATA = JSON.parse(read("data/local-files.json"));

const MAX_FILE = 2 * 1024 * 1024;
const BUDGET = 750 * 1024 * 1024;

/* Mirrors scripts/build-local-list.py, so a stale list is caught here. */
function renderList(entries) {
  const rows = entries.map((entry) => {
    const parts = ["file: " + JSON.stringify(entry.file), "title: " + JSON.stringify(entry.title)];
    if (entry.line) parts.push("line: " + JSON.stringify(entry.line));
    if (entry.featured) parts.push("featured: true");
    const source = entry.source || {};
    if (source.year) parts.push("year: " + source.year);
    if (source.author) parts.push("author: " + JSON.stringify(source.author));
    return "    { " + parts.join(", ") + " },";
  });
  return (
    "/* Shared list of locally hosted HTML files for both search pages.\n" +
    "   GENERATED from data/local-files.json by scripts/build-local-list.py.\n" +
    "   Do not edit this file: edit the JSON and re-run the script, or let\n" +
    "   .github/workflows/import-files.yml do it. */\n\n" +
    "window.LOCAL_GAMES = [\n" +
    rows.join("\n") +
    "\n];\n"
  );
}

/* Resource references a document would actually fetch. */
const RESOURCE = /(?:src|href|poster)\s*=\s*["']([^"']+)["']/gi;
const STYLE_BLOCK = /<style[^>]*>([\s\S]*?)<\/style>/gi;
const CSS_URL = /url\(\s*["']?([^"')]+)["']?\s*\)/gi;

function fetchedFrom(html) {
  const refs = [];
  for (const match of html.matchAll(RESOURCE)) {
    const value = match[1].trim();
    if (!value || /^(data:|#|mailto:|javascript:)/i.test(value)) continue;
    refs.push(value);
  }
  for (const block of html.matchAll(STYLE_BLOCK)) {
    for (const match of block[1].matchAll(CSS_URL)) {
      const value = match[1].trim();
      if (value && !/^data:/i.test(value)) refs.push(value);
    }
  }
  return refs;
}

function fileChecks(check) {
  console.log("\nFILES — the offline library and its importer\n");

  const entries = DATA.entries;
  check("the file list is not empty", entries.length > 0, String(entries.length));

  /* Every entry has a file, and nothing on disk is missing from the list. */
  const missing = entries.filter((entry) => !fs.existsSync(path.join(ROOT, entry.file)));
  check(
    "every listed file exists",
    missing.length === 0,
    missing.slice(0, 3).map((e) => e.file).join(", ")
  );

  const listed = new Set(entries.map((entry) => entry.file));
  const onDisk = fs
    .readdirSync(path.join(ROOT, "assets", "games"))
    .filter((name) => /\.html?$/.test(name))
    .map((name) => "assets/games/" + name);
  const orphans = onDisk.filter((rel) => !listed.has(rel));
  check(
    "every bundled file is listed",
    orphans.length === 0,
    orphans.slice(0, 3).join(", ")
  );

  /* Paths and titles are unique, or two cards fight over one entry. */
  for (const [name, key] of [["file paths", "file"], ["titles", "title"]]) {
    const values = entries.map((entry) => entry[key].toLowerCase());
    check(
      "no two entries share " + name,
      new Set(values).size === values.length,
      String(values.length - new Set(values).size) + " duplicates"
    );
  }

  /* Sizes. A game is a file, not a bundle of files. */
  const tooBig = entries.filter((entry) => {
    if ((entry.source || {}).kind !== "js13k") return false;
    return fs.statSync(path.join(ROOT, entry.file)).size > MAX_FILE;
  });
  check("no imported file is over 2 MB", tooBig.length === 0, tooBig.slice(0, 3).map((e) => e.file).join(", "));

  const total = entries.reduce((sum, entry) => sum + fs.statSync(path.join(ROOT, entry.file)).size, 0);
  check(
    "the library stays inside the page budget",
    total < BUDGET,
    (total / 1048576).toFixed(0) + " MB of " + BUDGET / 1048576 + " MB"
  );

  /* The promise the whole page makes: a file that needs nothing but itself. */
  const imported = entries.filter((entry) => (entry.source || {}).kind === "js13k");
  const leaky = imported.filter((entry) => {
    const refs = fetchedFrom(read(entry.file));
    return refs.some((ref) => !/^(data:|#)/i.test(ref));
  });
  check(
    "every imported file is self-contained",
    leaky.length === 0,
    leaky.slice(0, 3).map((e) => e.file).join(", ")
  );

  /* Attribution: these are other people's games. */
  const unattributed = imported.filter((entry) => {
    const source = entry.source || {};
    return !source.author || !source.repo || !source.year || !/^https:\/\/github\.com\//.test(source.repo);
  });
  check(
    "every imported game names its author and source",
    unattributed.length === 0,
    unattributed.slice(0, 3).map((e) => e.file).join(", ")
  );

  const noThumb = imported.filter(
    (entry) => !fs.existsSync(path.join(ROOT, "assets", "img", "pack", path.basename(entry.file, path.extname(entry.file)) + ".jpg"))
  );
  check(
    "every imported game has a card image",
    noThumb.length === 0,
    noThumb.slice(0, 3).map((e) => path.basename(e.file)).join(", ")
  );

  /* The generated list must match the JSON it is generated from. */
  check(
    "local-games.js matches data/local-files.json",
    read("assets/js/local-games.js") === renderList(entries),
    "run python3 scripts/build-local-list.py"
  );

  /* And the page really reads it. */
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(read("assets/js/local-games.js"), sandbox);
  const list = sandbox.window.LOCAL_GAMES || [];
  check("the page script loads every entry", list.length === entries.length, list.length + " vs " + entries.length);
  check(
    "the entries the page loads point at real files",
    list.every((game) => fs.existsSync(path.join(ROOT, game.file)))
  );

  /* The importer is configured to run unattended and to stop before the site
     outgrows what GitHub Pages will serve. */
  const workflow = read(".github/workflows/import-files.yml");
  check("a scheduled job keeps importing", /schedule:/.test(workflow) && /import-js13k\.py/.test(workflow));
  check("the job commits what it finds", /git push/.test(workflow));
  const importer = read("scripts/import-js13k.py");
  check(
    "the importer has a hard budget",
    /--budget-mb/.test(importer) && /budget/.test(importer)
  );
  check("the importer refuses files that still fetch", /def leftovers|def check/.test(importer));
}

module.exports = { fileChecks };
